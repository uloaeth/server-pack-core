package com.serverpackcore.agent;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Generates and launches the detached swap/rollback helper. The helper outlives the
 * agent, waits for it, replaces the jar, restarts and reverts when the new one does
 * not come up.
 */
public final class UpdateHelper {
	public static final String MODE_UPDATE = "update";
	public static final String MODE_ROLLBACK = "rollback";

	private static final String UNIX_NAME = "spc-update.sh";
	private static final String WINDOWS_NAME = "spc-update.vbs";

	private UpdateHelper() {
	}

	static String shQuote(String value) {
		return "'" + value.replace("'", "'\\''") + "'";
	}

	static String renderUnix(Path dir, Path current, Path newFile, Path oldFile, Path badFile, Path alive, Path java,
		Path gameDir, String version, String mode) {
		String helper = dir.resolve(UNIX_NAME).toString();
		String out = dir.resolve("spc-update.out").toString();
		String log = dir.resolve("update.log").toString();
		String game = gameDir == null ? "" : gameDir.toString();
		String javaHome = Path.of(System.getProperty("java.home", "")).toString();
		StringBuilder script = new StringBuilder();
		script.append("#!/bin/sh\n");
		script.append("# Generated by Server Pack Core. Deletes itself when done.\n");
		script.append("MODE=").append(shQuote(mode)).append('\n');
		script.append("VERSION=").append(shQuote(version)).append('\n');
		script.append("CUR=").append(shQuote(current.toString())).append('\n');
		script.append("NEW=").append(shQuote(newFile.toString())).append('\n');
		script.append("OLD=").append(shQuote(oldFile.toString())).append('\n');
		script.append("BAD=").append(shQuote(badFile.toString())).append('\n');
		script.append("ALIVE=").append(shQuote(alive.toString())).append('\n');
		script.append("JAVA=").append(shQuote(java.toString())).append('\n');
		script.append("GAME=").append(shQuote(game)).append('\n');
		script.append("HELPER=").append(shQuote(helper)).append('\n');
		script.append("LOG=").append(shQuote(log)).append('\n');
		script.append("OUT=").append(shQuote(out)).append('\n');
		script.append("OLD_PID=").append(oldPid(alive)).append('\n');
		script.append("export JAVA_HOME=").append(shQuote(javaHome)).append('\n');
		script.append("NEW_PID=''\n");
		script.append('\n');
		script.append("log() {\n");
		script.append("\tprintf '%s version=%s sha=- status=%s\\n' \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\"")
			.append(" \"$VERSION\" \"$1\" >> \"$LOG\"\n");
		script.append("}\n");
		script.append('\n');
		script.append("alive_pid() {\n");
		script.append("\t[ -f \"$ALIVE\" ] || return 1\n");
		script.append("\tsed -n 's/^agent=//p' \"$ALIVE\" 2>/dev/null | head -n 1\n");
		script.append("}\n");
		script.append('\n');
		script.append("launch() {\n");
		script.append("\tset -- -Xmx96m -jar \"$CUR\"\n");
		script.append("\t[ -n \"$GAME\" ] && set -- \"$@\" --game-dir \"$GAME\"\n");
		script.append("\tif command -v setsid >/dev/null 2>&1; then\n");
		script.append("\t\tsetsid \"$JAVA\" \"$@\" </dev/null >>\"$OUT\" 2>&1 &\n");
		script.append("\telse\n");
		script.append("\t\tnohup \"$JAVA\" \"$@\" </dev/null >>\"$OUT\" 2>&1 &\n");
		script.append("\tfi\n");
		script.append("\tNEW_PID=$!\n");
		script.append("}\n");
		script.append('\n');
		script.append("restore() {\n");
		script.append("\tif [ \"$MODE\" = update ]; then\n");
		script.append("\t\t[ -f \"$CUR\" ] && cp -f \"$CUR\" \"$BAD\"\n");
		script.append("\t\tcp -f \"$OLD\" \"$CUR\"\n");
		script.append("\telse\n");
		script.append("\t\t[ -f \"$BAD\" ] && cp -f \"$BAD\" \"$CUR\"\n");
		script.append("\tfi\n");
		script.append("}\n");
		script.append('\n');
		script.append("i=0\n");
		script.append("while [ \"$i\" -lt 30 ]; do\n");
		script.append("\tkill -0 \"$OLD_PID\" 2>/dev/null || break\n");
		script.append("\ti=$((i + 1))\n");
		script.append("\tsleep 1\n");
		script.append("done\n");
		script.append("kill -9 \"$OLD_PID\" 2>/dev/null\n");
		script.append("rm -f \"$ALIVE\"\n");
		script.append('\n');
		script.append("if [ \"$MODE\" = update ]; then\n");
		script.append("\trm -f \"$BAD\"\n");
		script.append("\t[ -f \"$CUR\" ] && mv -f \"$CUR\" \"$OLD\"\n");
		script.append("\tmv -f \"$NEW\" \"$CUR\"\n");
		script.append("else\n");
		script.append("\tcp -f \"$CUR\" \"$BAD\"\n");
		script.append("\tcp -f \"$OLD\" \"$CUR\"\n");
		script.append("fi\n");
		script.append('\n');
		script.append("launch\n");
		script.append('\n');
		script.append("i=0\n");
		script.append("OK=0\n");
		script.append("while [ \"$i\" -lt 30 ]; do\n");
		script.append("\tPID=$(alive_pid)\n");
		script.append("\tif [ -n \"$PID\" ] && [ \"$PID\" != \"$OLD_PID\" ] && kill -0 \"$PID\" 2>/dev/null; then\n");
		script.append("\t\tNEW_PID=\"$PID\"\n");
		script.append("\t\tOK=1\n");
		script.append("\t\tbreak\n");
		script.append("\tfi\n");
		script.append("\ti=$((i + 1))\n");
		script.append("\tsleep 1\n");
		script.append("done\n");
		script.append('\n');
		script.append("if [ \"$OK\" = 1 ]; then\n");
		script.append("\tsleep 20\n");
		script.append("\tPID=$(alive_pid)\n");
		script.append("\tif [ \"$PID\" = \"$NEW_PID\" ] && kill -0 \"$NEW_PID\" 2>/dev/null; then\n");
		script.append("\t\tlog ok\n");
		script.append("\t\trm -f \"$NEW\" \"$HELPER\"\n");
		script.append("\t\texit 0\n");
		script.append("\tfi\n");
		script.append("fi\n");
		script.append('\n');
		script.append("PID=$(alive_pid)\n");
		script.append("[ -n \"$PID\" ] && [ \"$PID\" != \"$OLD_PID\" ] && kill -9 \"$PID\" 2>/dev/null\n");
		script.append("[ -n \"$NEW_PID\" ] && kill -9 \"$NEW_PID\" 2>/dev/null\n");
		script.append("i=0\n");
		script.append("while [ \"$i\" -lt 10 ]; do\n");
		script.append("\tALIVE_NEW=0\n");
		script.append("\t[ -n \"$PID\" ] && kill -0 \"$PID\" 2>/dev/null && ALIVE_NEW=1\n");
		script.append("\t[ -n \"$NEW_PID\" ] && kill -0 \"$NEW_PID\" 2>/dev/null && ALIVE_NEW=1\n");
		script.append("\t[ \"$ALIVE_NEW\" = 0 ] && break\n");
		script.append("\ti=$((i + 1))\n");
		script.append("\tsleep 1\n");
		script.append("done\n");
		script.append("rm -f \"$ALIVE\"\n");
		script.append("restore\n");
		script.append("launch\n");
		script.append("log rollback\n");
		script.append("rm -f \"$HELPER\"\n");
		script.append("exit 1\n");
		return script.toString();
	}

	static String renderWindows(Path dir, Path current, Path newFile, Path oldFile, Path badFile, Path alive, Path java,
		Path gameDir, String version, String mode) {
		String helper = dir.resolve(WINDOWS_NAME).toString();
		String log = dir.resolve("update.log").toString();
		String game = gameDir == null ? "" : gameDir.toString();
		String javaHome = Path.of(System.getProperty("java.home", "")).toString();
		StringBuilder script = new StringBuilder();
		script.append("Option Explicit\n");
		script.append("Const MODE = ").append(vb(mode)).append('\n');
		script.append("Const VERSION = ").append(vb(version)).append('\n');
		script.append("Const CUR = ").append(vb(current.toString())).append('\n');
		script.append("Const NEW = ").append(vb(newFile.toString())).append('\n');
		script.append("Const OLD = ").append(vb(oldFile.toString())).append('\n');
		script.append("Const BAD = ").append(vb(badFile.toString())).append('\n');
		script.append("Const ALIVE = ").append(vb(alive.toString())).append('\n');
		script.append("Const JAVA = ").append(vb(java.toString())).append('\n');
		script.append("Const GAME = ").append(vb(game)).append('\n');
		script.append("Const HELPER = ").append(vb(helper)).append('\n');
		script.append("Const LOG = ").append(vb(log)).append('\n');
		script.append("Const JAVA_HOME = ").append(vb(javaHome)).append('\n');
		script.append("Const OLD_PID = ").append(oldPid(alive)).append('\n');
		script.append('\n');
		script.append("Dim shell, fso, newPid\n");
		script.append("Set shell = CreateObject(\"WScript.Shell\")\n");
		script.append("Set fso = CreateObject(\"Scripting.FileSystemObject\")\n");
		script.append("newPid = \"\"\n");
		script.append('\n');
		script.append("Sub AppendLog(state)\n");
		script.append("\tDim file\n");
		script.append("\tSet file = fso.OpenTextFile(LOG, 8, True)\n");
		script.append("\tfile.WriteLine stamp() & \" version=\" & VERSION & \" sha=- status=\" & state\n");
		script.append("\tfile.Close\n");
		script.append("End Sub\n");
		script.append('\n');
		script.append("Function stamp()\n");
		script.append("\tstamp = Year(Now) & \"-\" & Pad(Month(Now)) & \"-\" & Pad(Day(Now)) & \"T\" & Pad(Hour(Now))")
			.append(" & \":\" & Pad(Minute(Now)) & \":\" & Pad(Second(Now)) & \"Z\"\n");
		script.append("End Function\n");
		script.append('\n');
		script.append("Function Pad(value)\n");
		script.append("\tIf value < 10 Then Pad = \"0\" & value Else Pad = value\n");
		script.append("End Function\n");
		script.append('\n');
		script.append("Function AlivePid()\n");
		script.append("\tDim file, line\n");
		script.append("\tAlivePid = \"\"\n");
		script.append("\tOn Error Resume Next\n");
		script.append("\tIf Not fso.FileExists(ALIVE) Then Exit Function\n");
		script.append("\tSet file = fso.OpenTextFile(ALIVE, 1)\n");
		script.append("\tDo Until file.AtEndOfStream\n");
		script.append("\t\tline = file.ReadLine\n");
		script.append("\t\tIf Left(line, 6) = \"agent=\" Then AlivePid = Mid(line, 7)\n");
		script.append("\tLoop\n");
		script.append("\tfile.Close\n");
		script.append("\tOn Error GoTo 0\n");
		script.append("End Function\n");
		script.append('\n');
		script.append("Function Running(pid)\n");
		script.append("\tDim service, list\n");
		script.append("\tRunning = False\n");
		script.append("\tIf pid = \"\" Then Exit Function\n");
		script.append("\tOn Error Resume Next\n");
		script.append("\tSet service = GetObject(\"winmgmts:\\\\.\\root\\cimv2\")\n");
		script.append("\tSet list = service.ExecQuery(\"SELECT ProcessId FROM Win32_Process WHERE ProcessId=\" & CLng(pid))\n");
		script.append("\tRunning = (Err.Number = 0) And (list.Count > 0)\n");
		script.append("\tOn Error GoTo 0\n");
		script.append("End Function\n");
		script.append('\n');
		script.append("Sub Launch()\n");
		script.append("\tDim command\n");
		script.append("\tcommand = \"\"\"\" & JAVA & \"\"\" -Xmx96m -jar \"\"\" & CUR & \"\"\"\"\n");
		script.append("\tIf GAME <> \"\" Then command = command & \" --game-dir \"\"\" & GAME & \"\"\"\"\n");
		script.append("\tshell.Environment(\"PROCESS\")(\"JAVA_HOME\") = JAVA_HOME\n");
		script.append("\tshell.Run command, 0, False\n");
		script.append("End Sub\n");
		script.append('\n');
		script.append("Sub Restore()\n");
		script.append("\tOn Error Resume Next\n");
		script.append("\tIf MODE = \"update\" Then\n");
		script.append("\t\tfso.CopyFile CUR, BAD, True\n");
		script.append("\t\tfso.CopyFile OLD, CUR, True\n");
		script.append("\tElse\n");
		script.append("\t\tfso.CopyFile BAD, CUR, True\n");
		script.append("\tEnd If\n");
		script.append("\tOn Error GoTo 0\n");
		script.append("End Sub\n");
		script.append('\n');
		script.append("Dim i, pid, ok\n");
		script.append("For i = 1 To 30\n");
		script.append("\tIf Not Running(CStr(OLD_PID)) Then Exit For\n");
		script.append("\tWScript.Sleep 1000\n");
		script.append("Next\n");
		script.append("shell.Run \"taskkill /f /pid \" & OLD_PID, 0, True\n");
		script.append("On Error Resume Next\n");
		script.append("fso.DeleteFile ALIVE, True\n");
		script.append("If MODE = \"update\" Then\n");
		script.append("\tfso.DeleteFile BAD, True\n");
		script.append("\tfso.DeleteFile OLD, True\n");
		script.append("\tIf fso.FileExists(CUR) Then fso.MoveFile CUR, OLD\n");
		script.append("\tfso.MoveFile NEW, CUR\n");
		script.append("Else\n");
		script.append("\tfso.CopyFile CUR, BAD, True\n");
		script.append("\tfso.CopyFile OLD, CUR, True\n");
		script.append("End If\n");
		script.append("On Error GoTo 0\n");
		script.append('\n');
		script.append("Launch\n");
		script.append('\n');
		script.append("ok = False\n");
		script.append("For i = 1 To 30\n");
		script.append("\tpid = AlivePid()\n");
		script.append("\tIf pid <> \"\" And pid <> CStr(OLD_PID) And Running(pid) Then\n");
		script.append("\t\tnewPid = pid\n");
		script.append("\t\tok = True\n");
		script.append("\t\tExit For\n");
		script.append("\tEnd If\n");
		script.append("\tWScript.Sleep 1000\n");
		script.append("Next\n");
		script.append('\n');
		script.append("If ok Then\n");
		script.append("\tWScript.Sleep 20000\n");
		script.append("\tIf AlivePid() = newPid And Running(newPid) Then\n");
		script.append("\t\tAppendLog \"ok\"\n");
		script.append("\t\tOn Error Resume Next\n");
		script.append("\t\tfso.DeleteFile NEW, True\n");
		script.append("\t\tfso.DeleteFile HELPER, True\n");
		script.append("\t\tOn Error GoTo 0\n");
		script.append("\t\tWScript.Quit 0\n");
		script.append("\tEnd If\n");
		script.append("End If\n");
		script.append('\n');
		script.append("If newPid <> \"\" Then shell.Run \"taskkill /f /pid \" & newPid, 0, True\n");
		script.append("On Error Resume Next\n");
		script.append("fso.DeleteFile ALIVE, True\n");
		script.append("On Error GoTo 0\n");
		script.append("Restore\n");
		script.append("Launch\n");
		script.append("AppendLog \"rollback\"\n");
		script.append("On Error Resume Next\n");
		script.append("fso.DeleteFile HELPER, True\n");
		script.append("WScript.Quit 1\n");
		return script.toString();
	}

	static Path write(Path dir, String mode, String version, Path gameDir) throws UpdateException {
		boolean windows = AgentPaths.isWindows();
		Path helper = dir.resolve(windows ? WINDOWS_NAME : UNIX_NAME);
		Path java = Path.of(System.getProperty("java.home", ""), "bin", windows ? "javaw.exe" : "java");
		String text = windows
			? renderWindows(dir, dir.resolve("spc-agent.jar"), dir.resolve(Update.STAGED_NAME),
				dir.resolve(Update.OLD_NAME), dir.resolve(Update.BAD_NAME), dir.resolve("alive.txt"), java, gameDir,
				version, mode)
			: renderUnix(dir, dir.resolve("spc-agent.jar"), dir.resolve(Update.STAGED_NAME),
				dir.resolve(Update.OLD_NAME), dir.resolve(Update.BAD_NAME), dir.resolve("alive.txt"), java, gameDir,
				version, mode);
		try {
			Files.createDirectories(dir);
			if (windows) {
				ByteArrayOutputStream bytes = new ByteArrayOutputStream();
				bytes.write(0xFF);
				bytes.write(0xFE);
				bytes.write(text.getBytes(StandardCharsets.UTF_16LE));
				Files.write(helper, bytes.toByteArray());
			} else {
				Files.writeString(helper, text, StandardCharsets.UTF_8);
				helper.toFile().setExecutable(true, true);
			}
			return helper;
		} catch (IOException exception) {
			throw new UpdateException("helper write failed");
		}
	}

	static void launch(Path dir, Path helper) throws UpdateException {
		try {
			ProcessBuilder builder;
			if (AgentPaths.isWindows()) {
				builder = new ProcessBuilder("wscript.exe", "//nologo", helper.toString());
			} else if (Files.isExecutable(Path.of("/usr/bin/setsid"))) {
				builder = new ProcessBuilder("/usr/bin/setsid", "/bin/sh", helper.toString());
			} else {
				builder = new ProcessBuilder("/bin/sh", helper.toString());
			}
			builder.directory(dir.toFile());
			builder.redirectErrorStream(true);
			builder.redirectOutput(ProcessBuilder.Redirect.appendTo(dir.resolve("spc-update.out").toFile()));
			builder.start();
		} catch (IOException exception) {
			throw new UpdateException("helper launch failed");
		}
	}

	private static String vb(String value) {
		return "\"" + value.replace("\"", "\"\"") + "\"";
	}

	/** The running agent PID comes from alive.txt; the current process is only a fallback. */
	private static long oldPid(Path alive) {
		try {
			if (Files.isRegularFile(alive)) {
				for (String line : Files.readAllLines(alive, StandardCharsets.UTF_8)) {
					if (line.startsWith("agent=")) {
						return Long.parseLong(line.substring(6).trim());
					}
				}
			}
		} catch (Throwable throwable) {
			Log.debug("Old pid read failed", throwable);
		}
		return ProcessHandle.current().pid();
	}
}
