	static Path writeMod(Path dir, Path mods, Path staged, Path target, String version, String mode)
		throws UpdateException {
		return writeMod(dir, mods, staged, target, version, mode, nextModGeneration(dir));
	}

	static Path writeMod(Path dir, Path mods, Path staged, Path target, String version, String mode, long generation)
		throws UpdateException {
		boolean windows = AgentPaths.isWindows();
		Path helper = AgentPaths.modHelper(dir);
		Path temp = dir.resolve(helper.getFileName() + ".tmp");
		String text = windows
			? renderModWindows(dir, mods, staged, target, AgentPaths.alive(dir), version, mode, generation)
			: renderModUnix(dir, mods, staged, target, AgentPaths.alive(dir), version, mode, generation);
		try {
			Files.createDirectories(dir);
			Files.createDirectories(AgentPaths.log(dir).getParent());
			if (windows) {
				ByteArrayOutputStream bytes = new ByteArrayOutputStream();
				bytes.write(0xFF);
				bytes.write(0xFE);
				bytes.write(text.getBytes(StandardCharsets.UTF_16LE));
				Files.write(temp, bytes.toByteArray());
			} else {
				Files.writeString(temp, text, StandardCharsets.UTF_8);
			}
			try {
				Files.move(temp, helper, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
			} catch (IOException atomicFailed) {
				Files.move(temp, helper, StandardCopyOption.REPLACE_EXISTING);
			}
			if (!windows) {
				helper.toFile().setExecutable(true, true);
			}
			return helper;
		} catch (IOException exception) {
			throw new UpdateException("mod helper write failed");
		}
	}

	static Path write(Path dir, String mode, String version, Path gameDir) throws UpdateException {
		boolean windows = AgentPaths.isWindows();
		Path helper = AgentPaths.helper(dir);
		Path java = Path.of(System.getProperty("java.home", ""), "bin", windows ? "javaw.exe" : "java");
		String text = windows
			? renderWindows(dir, AgentPaths.agentJar(dir), AgentPaths.agentStaged(dir),
				AgentPaths.agentOld(dir), AgentPaths.agentBad(dir), AgentPaths.alive(dir), java, gameDir,
				version, mode)
			: renderUnix(dir, AgentPaths.agentJar(dir), AgentPaths.agentStaged(dir),
				AgentPaths.agentOld(dir), AgentPaths.agentBad(dir), AgentPaths.alive(dir), java, gameDir,
				version, mode);
		try {
			Files.createDirectories(dir);
			Files.createDirectories(AgentPaths.log(dir).getParent());
			if (windows) {
				ByteArrayOutputStream bytes = new ByteArrayOutputStream();
				bytes.write(0xFF);
				bytes.write(0xFE);
				bytes.write(text.getBytes(StandardCharsets.UTF_16LE));
				Files.write(helper, bytes.toByteArray());
			} else {
				Files.writeString(helper, text, StandardCharsets.UTF_8);
				helper.toFile().setExecutable(true, true);
			}
			return helper;
		} catch (IOException exception) {
			throw new UpdateException("helper write failed");
		}
	}

	static void launch(Path dir, Path helper) throws UpdateException {
		try {
			ProcessBuilder builder;
			if (AgentPaths.isWindows()) {
				builder = new ProcessBuilder("wscript.exe", "//nologo", helper.toString());
			} else if (Files.isExecutable(Path.of("/usr/bin/setsid"))) {
				builder = new ProcessBuilder("/usr/bin/setsid", "/bin/sh", helper.toString());
			} else {
				builder = new ProcessBuilder("/bin/sh", helper.toString());
			}
			builder.directory(dir.toFile());
			builder.redirectErrorStream(true);
			builder.redirectOutput(ProcessBuilder.Redirect.appendTo(AgentPaths.out(dir).toFile()));
			builder.start();
		} catch (IOException exception) {
			throw new UpdateException("helper launch failed");
		}
	}

